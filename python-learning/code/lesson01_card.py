"""
第 1 次课 · 个人名片生成器
================================

这是你的第一个 Python 程序：它会问你三个问题，然后打印一张「名片」。

【怎么运行】
  方式一（推荐）：双击 code 文件夹里的 start.bat，然后输入 1
  方式二：在本文件夹打开终端，输入  python lesson01_card.py

【这节课用到的知识点】
  print()      把内容显示在屏幕上
  input()      暂停程序，等你输入一句话
  变量          给一份数据起个名字
  int()        把「文字」变成「整数」
  f-string     把变量塞进一句话里
  注释          以 # 开头的行，Python 会跳过不执行
"""

# print() 是最简单的输出函数。
# "=" * 40 的意思是：把等号重复 40 遍，用来画一条分隔线。
print("=" * 40)
print("         个人名片生成器")
print("=" * 40)
print()      # 空的 print() 就是输出一个空行

# ---------------------------------------------------------------
# input() 会暂停程序，等你敲完字、按回车，才继续往下走。
# 括号里的那句话叫「提示语」，会显示在屏幕上。
#
# 最重要的一个坑：input() 拿到的永远是「字符串」（文字）。
# 哪怕你输入的是 20，它拿到的也是 "20" 而不是数字 20。
# ---------------------------------------------------------------
name = input("请输入你的名字：")

# 年龄要参与加减计算，所以必须用 int() 把文字转成整数。
# 如果这里不写 int()，最后一行 age + 1 会报 TypeError。
age = int(input("请输入你的年龄："))

city = input("请输入你所在的城市：")

# ---------------------------------------------------------------
# f-string：在引号前面加一个小写的 f，
# 然后用花括号 {变量名} 把变量的值嵌进句子里。
# 这是把变量和文字拼在一起最省事的写法。
# ---------------------------------------------------------------
print()
print("-" * 40)
print(f"你好，{name}！")
print(f"你今年 {age} 岁，来自 {city}。")
print(f"明年你就 {age + 1} 岁了。")

# len() 用来看一串文字有几个字
print(f"你的名字有 {len(name)} 个字，城市名有 {len(city)} 个字。")
print("-" * 40)
print()
print("名片生成完毕。")

