"""
第 2 次课 · 猜数字小游戏
==========================

程序偷偷想一个 1~100 之间的整数，你来猜。
每猜一次，它会告诉你「大了」还是「小了」，直到猜对为止。

【怎么运行】
  方式一：双击 start.bat，输入 2
  方式二：python lesson02_guess.py

【这节课用到的知识点】
  import              借用别人写好的工具箱（random 负责生成随机数）
  if / elif / else    让程序学会做选择
  while True          一直循环，直到遇到 break
  break               立刻跳出循环
  比较运算符           >   <   ==
"""

import random      # random 是 Python 自带的工具箱，专门管随机数

print("=" * 40)
print("         猜数字小游戏")
print("=" * 40)

# random.randint(1, 100) 会随机吐出一个 1 到 100 之间的整数（含两端）
secret = random.randint(1, 100)

count = 0          # 用来记录你猜了几次

print("我已经想好了一个 1 到 100 之间的整数。")
print("看看你需要几次才能猜中？")
print()

# while True 的意思是：只要条件为真就一直转圈。
# 因为 True 永远为真，所以它会一直转 —— 直到遇到 break 才停下来。
while True:
    # input() 拿到的是文字，要比较大小必须先转成整数
    guess = int(input("请输入你猜的数字："))
    count = count + 1          # 也可以写成 count += 1，效果一样

    # if / elif / else 是「三岔路口」：
    # 从上往下逐个检查，第一个成立的分支执行完就跳出整个 if。
    if guess > secret:
        print("大了！往小一点猜。")
    elif guess < secret:
        print("小了！往大一点猜。")
    else:
        print()
        print(f"猜对了！答案就是 {secret}。")
        print(f"你一共猜了 {count} 次。")

        # 在 else 里面还可以再嵌一层 if —— 这叫「嵌套」
        if count <= 5:
            print("太厉害了，运气和直觉都在线！")
        elif count <= 8:
            print("不错，中规中矩。")
        else:
            print("有点辛苦。不过你刚好亲身体验了「二分法」的价值：")
            print("每次都猜中间值，最多 7 次就能锁定 1~100 里的任何一个数。")
        print()
        break      # 跳出 while 循环，程序结束

# ===============================================================
# 这节课的三个关键点：
#
#   1. 缩进（每行前面的空格）不是装饰，是语法。
#      if 下面那几行必须缩进，才能表示「它们属于这个 if」。
#      同一个块里的缩进必须一样多，Python 官方推荐 4 个空格。
#      缩进写错会直接报错 IndentationError —— 这是新手最常见的错误。
#
#   2. while True 配 break，是「事先不知道要转几圈」时的标准写法。
#      如果你知道要转几圈（比如「输出 5 次」），用 for 循环更合适。
#
#   3. 如果输入的不是数字（比如打了个 abc），程序会直接报错停下。
#      这是正常的，第 4 次课我们会学会看懂这类报错。
#
