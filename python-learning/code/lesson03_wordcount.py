"""
第 3 次课 · 英文文章词频统计
==============================

给一段英文，统计每个单词出现了多少次，并打印前 5 名。

这个程序是后面「文本的数字化 / 词袋模型」的手工版 ——
原理完全一样，只是后面会换成现成的库函数。

【怎么运行】
  方式一：双击 start.bat，输入 3
  方式二：python lesson03_wordcount.py

【这节课用到的知识点】
  列表 list      有顺序的一串数据，用 [] 表示
  字典 dict      存「什么 → 多少」的对应关系，用 {} 表示
  for 循环       把一串东西挨个处理一遍
  sorted()       排序
"""

# 先把要统计的英文放在一个三引号字符串里。
# 三引号 """...""" 可以跨很多行，写长文本很方便。
TEXT = """
Python is a programming language that lets you work quickly
and integrate systems more effectively. Python is powerful and fast.
Python plays well with others. Python runs everywhere.
Python is friendly and easy to learn. Python is open.
"""

print("=" * 46)
print("           英文文章词频统计")
print("=" * 46)
print()

# ---------------------------------------------------------------
# 第 1 步：清洗 —— 转成小写。
# 这样 "Python" 和 "python" 会被当成同一个词，不会分开统计。
# ---------------------------------------------------------------
text = TEXT.lower()

# ---------------------------------------------------------------
# 第 2 步：切分 —— 把一整段文字拆成一个个单词。
#
# split() 不写参数时，会按「空白字符」（空格、换行、制表符）切开，
# 结果是一个列表（list）。
# 注意：英文靠空格天然分好词，中文不行 —— 这正是第 4 次课要解决的问题。
# ---------------------------------------------------------------
words = text.split()
print(f"切分后一共拿到 {len(words)} 个「词」")
print(f"前 8 个是：{words[:8]}")     # [:8] 表示「取前 8 个」
print()

# ---------------------------------------------------------------
# 第 3 步：去掉标点。
# 英文的句号、逗号会粘在单词屁股后面（比如 effectively.），
# 所以要把这些符号从每个词的两头削掉。
# strip("要去掉的字符") 就是干这个的。
# ---------------------------------------------------------------
cleaned = []       # 准备一个空列表，用来装清洗干净的结果

for w in words:
    w = w.strip(".,!?;:\"'()")     # 把两头这些符号削掉
    if w != "":                     # 削完可能变成空字符串，要跳过
        cleaned.append(w)           # append() 是「往列表末尾追加一个」

print(f"去掉标点后还剩 {len(cleaned)} 个词")
print()

# ---------------------------------------------------------------
# 第 4 步：统计次数 —— 这一步用的就是「字典」。
#
# 字典存的是「键 → 值」的对应关系，这里就是「单词 → 出现次数」。
# 思路：挨个看每个词 ——
#       字典里已经有它？就把次数加 1。
#       还没有？就把它记进去，次数从 1 开始。
#
# 这就是「词袋模型（Bag of Words）」最朴素的手工版：
# 只关心有哪些词、各出现几次，完全不关心词的顺序。
# ---------------------------------------------------------------
counts = {}        # 空字典

for w in cleaned:
    if w in counts:              # 已经在字典里了？
        counts[w] = counts[w] + 1     # 次数加一
    else:
        counts[w] = 1                 # 第一次见到，记成 1

print(f"一共有 {len(counts)} 个不重复的词")
print()

# ---------------------------------------------------------------
# 第 5 步：排序，取前 5 名。
#
# counts.items() 会把字典变成一串「(词, 次数)」这样的配对。
# sorted(...) 负责排序；key=... 告诉它「按什么排」：
#     这里的 pair[1] 指的是配对的第 2 个元素，也就是「次数」。
#     reverse=True 表示从大到小排。
#
# 那个 lambda 看不懂完全没关系 —— 它是一个「现写现用的小规则」，
# 先照着抄，第 4 次课讲完函数就懂了。
# ---------------------------------------------------------------
items = sorted(counts.items(), key=lambda pair: pair[1], reverse=True)

print("出现次数最多的 5 个单词：")
print("-" * 46)
for i in range(5):
    word, n = items[i]          # 把配对拆成「词」和「次数」两个变量
    bar = "=" * n               # 用等号画一个简易柱状图
    print(f"  {i+1}. {word:<14}{n} 次   {bar}")
    # 上面 {word:<14} 的意思是：把这个词占 14 格宽、左边对齐，
    # 这样后面几列就能对齐好看。不用管它，知道是「排版用」就行。
print("-" * 46)

# 小提示：看到 "the" / "and" / "is" 这类词排在最前面了吗？
# 它们出现得多，但并不代表文章在讲什么 ——
# 这类词叫「停用词（stop words）」，真实项目里通常要先过滤掉。
# 这也是第 5 次课会讲的内容。

