# 为我讲解注释
# ------------------------------------------------------------------
# 上面那一行，是你自己写的注释 —— 其实你已经在用注释了。
# 下面用 6 个小例子，把「注释」这件事讲清楚。
# 运行方法：点编辑区右上角的 ▶（或按 Ctrl + F5），结果显示在下面的终端里。
# ------------------------------------------------------------------


# 例子 1：这一整行都是注释，Python 完全不理它
print("1. 我是真正的代码，所以你会看到我")


# 例子 2：在行首加一个 #，这行就被「停用」了
# print("2. 我被注释掉了，你看不到我")
print("2. 上面那行被停用，所以只跑出来我这一行")


# 例子 3：注释也可以写在代码的右边
print("3. 代码照常执行")          # 而从 # 到行尾这一段是注释，Python 不看


# 例子 4：引号里的 # 不是注释，它只是普通文字
print("4. 我这里有个 # 号，但它只是普通字符，照样打印")


# 例子 5：想写多行，就每一行开头都加一个 #
#         Python 并没有「多行注释」这个语法，
#         所谓多行注释，就是「一行一个 #」。
print("5. 多行注释 = 每行都加 #")


# 例子 6：三个引号不是注释，它是一段「字符串」
s = """
这段文字看着像注释，
其实它是一段真正的字符串，被装进了变量 s。
"""
print("6. 变量 s 里装的是下面这些内容：")
print(s.strip())        # strip() 只是去掉开头和结尾的空行


print("---- 全部跑完啦 ----")


# 最后一句心得：写注释别写「print 是打印」这种一看就懂的，
# 要写「为什么要这么做」。三个月后看不懂自己代码的人，缺的都是这一句。
